const dictionaries: Record<Lang, Dict> = { pt, en, fr, ar };

const STORAGE_KEY = "caiat.lang";
const listeners = new Set<() => void>();

let currentLang: Lang = "en";

export function getLang(): Lang {
  return currentLang;
}

export function isRTL(lang: Lang = currentLang): boolean {
  return lang === "ar";
}

function isLang(value: unknown): value is Lang {
  return value === "pt" || value === "en" || value === "fr" || value === "ar";
}

function storedLang(): Lang | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    return isLang(raw) ? raw : null;
  } catch {
    return null;
  }
}

function applyDocumentLang(lang: Lang) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = lang;
  document.documentElement.dir = isRTL(lang) ? "rtl" : "ltr";
}

export function setLang(lang: Lang) {
  currentLang = lang;
  if (typeof window !== "undefined") {
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* private mode: language simply is not persisted */
    }
  }
  applyDocumentLang(lang);
  listeners.forEach((fn) => fn());
}

/** Translate a key, with `{placeholder}` interpolation and English fallback. */
export function t(key: TranslationKey, vars?: Record<string, string | number>): string {
  const value = dictionaries[currentLang]?.[key] ?? en[key] ?? String(key);
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] != null ? String(vars[name]) : match,
  );
}

/** Reactive access to the active language. */
export function useLang(): { lang: Lang; setLang: (l: Lang) => void } {
  const [lang, setLocal] = useState<Lang>(currentLang);

  useEffect(() => {
    const stored = storedLang();
    if (stored && stored !== currentLang) {
      setLang(stored);
    } else {
      applyDocumentLang(currentLang);
    }
    const listener = () => setLocal(getLang());
    listener();
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);

  const change = useCallback((next: Lang) => setLang(next), []);
  return { lang, setLang: change };
}

/**
 * Re-renders everything below it when the language changes, so plain `t()`
 * calls inside components always show the active locale.
 */
export function I18nProvider({ children }: { children: ReactNode }) {
  const { lang } = useLang();
  const { currency } = useCurrency();
  return <div key={`${lang}:${currency}`} className="contents">{children}</div>;
}

